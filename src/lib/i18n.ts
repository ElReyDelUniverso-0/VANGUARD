const DICTS: Record<Lang, Dict> = {
  es: ES, en: EN, pt: PT, fr: FR, de: DE, it: IT, ru: RU, zh: ZH,
};

// ===================== API PÚBLICA =====================

/** Devuelve la traducción de una clave con fallback: lang -> es -> clave */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang]?.[key] ?? DICTS.es[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/** Etiqueta del tab (subtema) en el idioma dado — fallback a español */
export function tabLabel(lang: Lang, key: string, fallback: string): string {
  return TAB_LABELS[lang]?.[key] ?? TAB_LABELS.es?.[key] ?? fallback;
}

/** Hook principal: t(clave, vars) ya vinculado al idioma del store.
 *  Puerta mounted: SSR y primer render usan "es" (sin hydration mismatch),
 *  el idioma elegido se aplica justo tras montar. */
export function useT() {
  const lang = useLangStore((s) => s.lang);
  const [mounted, setMounted] = useState(false);
  useEffect(() => setMounted(true), []);
  const effective = mounted ? lang : "es";
  return useMemo(() => {
    const t = (key: string, vars?: Record<string, string | number>) => translate(effective, key, vars);
    return { t, lang: effective, setLang: useLangStore.getState().setLang };
  }, [effective]);
}
