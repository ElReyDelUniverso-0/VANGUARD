// ===================== v193.0 LA CASA LIGERA — DICCIONARIOS DIFERIDOS =====
// El bundle inicial solo lleva ES (el idioma de la Casa). Los otros 7
// idiomas viven en src/lib/i18n/lang-*.ts y bajan SOLO si el agente los
// elige — el arranque pesa ~85 KB menos y la cortina se levanta antes.
// Mientras el diccionario viaja, translate() cae a es (fallback intacto)
// y al llegar se avisa con dicVersion para repintar sin recargar nada.
const DICTS: { es: Dict } & Partial<Record<Lang, Dict>> = { es: ES };

const CARGADORES: Record<Exclude<Lang, "es">, () => Promise<{ default: Dict }>> = {
  en: () => import("./i18n/lang-en"),
  pt: () => import("./i18n/lang-pt"),
  fr: () => import("./i18n/lang-fr"),
  de: () => import("./i18n/lang-de"),
  it: () => import("./i18n/lang-it"),
  ru: () => import("./i18n/lang-ru"),
  zh: () => import("./i18n/lang-zh"),
};

const enVuelo = new Map<Lang, Promise<void>>();

/** Trae el diccionario del idioma si falta; al llegar repinta (dicVersion). */
export function asegurarDiccionario(lang: Lang): void {
  try {
    if (lang === "es" || DICTS[lang] || enVuelo.has(lang)) return;
    const vuelo = CARGADORES[lang as Exclude<Lang, "es">]()
      .then((m) => {
        DICTS[lang] = m.default;
        enVuelo.delete(lang);
        try { useLangStore.setState({ dicVersion: Date.now() }); } catch { /* sin store aún */ }
      })
      .catch(() => { enVuelo.delete(lang); /* reintento en el próximo uso */ });
    enVuelo.set(lang, vuelo);
  } catch {
    /* el idioma jamás tumba la página */
  }
}

// ===================== API PÚBLICA =====================

/** Devuelve la traducción de una clave con fallback: lang -> es -> clave */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang]?.[key] ?? DICTS.es[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/** Etiqueta del tab (subtema) en el idioma dado — fallback a español */
export function tabLabel(lang: Lang, key: string, fallback: string): string {
  return TAB_LABELS[lang]?.[key] ?? TAB_LABELS.es?.[key] ?? fallback;
}

/** Hook principal: t(clave, vars) ya vinculado al idioma del store.
 *  Puerta mounted: SSR y primer render usan "es" (sin hydration mismatch),
 *  el idioma elegido se aplica justo tras montar. */
export function useT() {
  const lang = useLangStore((s) => s.lang);
  const dicVersion = useLangStore((s) => s.dicVersion);
  const [mounted, setMounted] = useState(false);
  useEffect(() => setMounted(true), []);
  const effective = mounted ? lang : "es";
  // v193.0: si el idioma elegido no es es, su diccionario diferido se trae
  // aquí (una sola vez); al aterrizar, dicVersion repinta los textos.
  useEffect(() => {
    if (effective !== "es") asegurarDiccionario(effective);
  }, [effective]);
  return useMemo(() => {
    const t = (key: string, vars?: Record<string, string | number>) => translate(effective, key, vars);
    return { t, lang: effective, setLang: useLangStore.getState().setLang };
  }, [effective, dicVersion]);
}
