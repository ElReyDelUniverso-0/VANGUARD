const DICCIONARIOS: Record<Lang, Dict> = { es: ES, en: EN, pt: PT, fr: FR, de: DE, it: IT, ru: RU, zh: ZH };

export function tRes(lang: Lang, clave: ResClave, vars?: Record<string, string | number>): string {
  const base = DICCIONARIOS[lang]?.[clave] ?? ES[clave];
  if (!vars) return base;
  return base.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}
