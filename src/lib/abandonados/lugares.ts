export const CATEGORIAS: CategoriaAbandono[] = ["ciudad", "hospital", "ocio", "industrial"];

export function lugarPorId(id: string): LugarAbandonado | undefined {
  return LUGARES.find((l) => l.id === id);
}

export function cifrasAbandono() {
  const paises = new Set(LUGARES.map((l) => l.iso2));
  const porCat = CATEGORIAS.map((c) => ({ categoria: c, cantidad: LUGARES.filter((l) => l.categoria === c).length }));
  const visitables = LUGARES.filter((l) => l.acceso.tipo === "visita-oficial").length;
  return { total: LUGARES.length, paises: paises.size, porCat, visitables };
}

/** Equirectangular sobre un lienzo 1000×500 (igual que /abandonados/mundo.svg). */
export function proyectar(lat: number, lon: number): { x: number; y: number } {
  return { x: ((lon + 180) / 360) * 1000, y: ((90 - lat) / 180) * 500 };
}
